/**
 * Writes a migration that seeds official grids into Postgres, using the same placement
 * code as the app so every square index matches the device.
 *
 *   npx tsx scripts/starter-sql.ts > supabase/migrations/20261025000002_starter_grids.sql
 *   npx tsx scripts/starter-sql.ts premade > supabase/migrations/20261030050000_premade_grids.sql
 */
import { STARTERS } from '../src/data/starters';
import { PREMADE } from '../src/data/premade';
import { kinderMemories } from '../src/data/premade/family';
import { SIZES, placeClusters } from '../src/data/types';

const grids = process.argv[2] === 'premade' ? [...PREMADE, kinderMemories] : STARTERS;
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const out: string[] = [
  '-- Generated by scripts/starter-sql.ts from src/data. Do not edit by hand.',
  '',
];
for (const g of grids) {
  const { cols, rows } = SIZES[g.size];
  out.push(
    `insert into public.grids (id, title, color, theme, size, cols, rows, description, made_by, is_official, is_public)`,
    `values (${q(g.id)}, ${q(g.title)}, ${q(g.color)}, ${q(g.theme)}, ${q(g.size)}, ${cols}, ${rows}, ${q(g.description)}, 'AirStrive', true, true)`,
    `on conflict (id) do update set title = excluded.title, color = excluded.color, theme = excluded.theme, description = excluded.description, updated_at = now();`,
    '',
    `insert into public.grid_squares (grid_id, idx, prompt, cluster) values`,
    placeClusters(g).map((s) => `  (${q(g.id)}, ${s.idx}, ${q(s.prompt)}, ${q(s.cluster)})`).join(',\n'),
    `on conflict (grid_id, idx) do update set prompt = excluded.prompt, cluster = excluded.cluster;`,
    '',
  );
}
process.stdout.write(out.join('\n'));
