/**
 * The reviewed prompt bank behind "Suggest the rest". Nothing here is generated at runtime:
 * every prompt was written and read by a person, in the same voice as the starter grids.
 *
 * Keywords are matched against a normalized grid name as word prefixes ("bike" finds
 * "biking"), so they avoid short stems that start unrelated words ("tea" would find "team").
 */

